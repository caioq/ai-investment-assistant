import { randomUUID } from 'node:crypto';
import type { Client } from 'pg';

/**
 * Deterministic seed data for `dashboard-visual.spec.ts`'s "populated
 * dashboard" screenshot (`VISUAL_REGRESSION_POPULATED_USER`, see
 * `./visual-regression-users.ts`). Written directly via a plain `pg` client
 * — the same tool `global-setup.ts` already uses for its fixture-user
 * teardown — rather than through the live API: `POST /portfolio/holdings`
 * would trigger `MarketDataService.findOrCreateAsset` -> `backfillHistory`,
 * which reaches out to the real, rate-limited, non-deterministic Yahoo
 * Finance endpoint. Direct DB writes are the only way to get fully pinned,
 * reproducible numbers for a committed screenshot baseline.
 *
 * `Asset`/`Holding`/`PortfolioValueSnapshot`/`BenchmarkSnapshot`/
 * `AdvisorAnalysis` rows all declare `id` with no DB-level default
 * (`@default(uuid(7))` is a Prisma **client-side** default, not a Postgres
 * `DEFAULT` — see the migration SQL) — every row below generates its own id
 * with `randomUUID()` rather than relying on the database to supply one.
 */

